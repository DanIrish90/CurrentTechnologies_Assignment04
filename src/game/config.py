def validate_worm_timer_configuration() -> None:
    """Reject invalid timing values before gameplay or rendering starts."""

    if WAVE_REST_DURATION <= 0:
        raise ValueError("WAVE_REST_DURATION must be positive")
    if WORM_TIMER_FPS <= 0:
        raise ValueError("WORM_TIMER_FPS must be positive")


def validate_ui_configuration() -> None:
    """Reject invalid presentation scales before the game starts."""

    if UI_STAMINA_BAR_SCALE <= 0:
        raise ValueError("UI_STAMINA_BAR_SCALE must be positive")
    if UI_FISHING_METER_WIDTH != UI_FISHING_BAR_WIDTH * 2:
        raise ValueError("FishingMeter width must contain the bar and icon column")
    if UI_FISHING_METER_HEIGHT < UI_FISHING_ICON_SIZE * UI_FISHING_ICON_COUNT:
        raise ValueError("FishingMeter height must contain all icon regions")
